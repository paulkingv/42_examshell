#!/usr/bin/env node
/*
 * Bundles exam subjects (from ../.resources) and the reference solutions
 * (from ./solutions) into data.js, which the game loads.
 *
 *   node game/build.js
 *
 * Solution files are split into chunks with marker comments:
 *   //# id | Title            -> a chunk the player has to memorise
 *   //# id | Title | given    -> code handed out by the exam (shown, not drilled)
 *
 * Logic notes feed the Logic box and the Logic tab:
 *   //! text                  -> what the block is for (one per block)
 *   //? step || why           -> plain-language step for the next code line; "|| why" is optional
 *   //~ text                  -> same, but the line is unchanged from the exam's file: shown, not drilled
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const res = (p) => fs.readFileSync(path.join(ROOT, '.resources', p), 'utf8');
const sol = (rank, f) => fs.readFileSync(path.join(__dirname, 'solutions', rank, f), 'utf8');

const RANKS = [
	{
		id: 'rank03',
		name: 'Exam Rank 03',
		levels: [
			{
				name: 'Level 1',
				exercises: [
					{ id: 'filter', name: 'filter', subject: 'rank03/level1/filter/sub.txt', solution: 'filter.c' },
					{ id: 'ft_scanf', name: 'ft_scanf', subject: 'rank03/level1/scanf/sub.txt', solution: 'ft_scanf.c' },
					{
						id: 'broken_gnl', name: 'broken_gnl', subject: 'rank03/level1/broken_gnl/sub.txt',
						solution: 'get_next_line.c', original: 'rank03/level1/broken_gnl/broken_gnl.c',
					},
				],
			},
			{
				name: 'Level 2',
				exercises: [
					{ id: 'n_queens', name: 'n_queens', subject: 'rank03/level2/n_queens/sub.txt', solution: 'n_queens.c' },
					{ id: 'permutations', name: 'permutations', subject: 'rank03/level2/permutations/sub.txt', solution: 'permutations.c' },
					{ id: 'powerset', name: 'powerset', subject: 'rank03/level2/powerset/sub.txt', solution: 'powerset.c' },
					{ id: 'rip', name: 'rip', subject: 'rank03/level2/rip/sub.txt', solution: 'rip.c' },
					{ id: 'tsp', name: 'tsp', subject: 'rank03/level2/tsp/sub.txt', solution: 'tsp.c' },
				],
			},
		],
	},
];

function parseChunks(src, file) {
	const chunks = [];
	let cur = null;
	let pending = null;
	for (const line of src.replace(/\r/g, '').split('\n')) {
		const m = line.match(/^\/\/#\s*(.+)$/);
		const note = line.match(/^\/\/([?!~])\s*(.+)$/);
		if (m) {
			const [id, title, flag] = m[1].split('|').map((s) => s.trim());
			cur = { id, title: title || id, given: flag === 'given', goal: '', lines: [], notes: [], ctx: [] };
			chunks.push(cur);
		} else if (note && cur) {
			if (note[1] === '!') cur.goal = note[2].trim();
			else pending = { text: note[2].split('||').map((s) => s.trim()), ctx: note[1] === '~' };
		} else if (cur) {
			cur.lines.push(line);
			cur.notes.push(pending && pending.text);
			cur.ctx.push(!!(pending && pending.ctx));
			pending = null;
		} else if (line.trim()) {
			throw new Error(`${file}: code before the first //# marker`);
		}
	}
	for (const c of chunks) {
		while (c.lines.length && !c.lines[0].trim()) { c.lines.shift(); c.notes.shift(); c.ctx.shift(); }
		while (c.lines.length && !c.lines[c.lines.length - 1].trim()) { c.lines.pop(); c.notes.pop(); c.ctx.pop(); }
		if (!c.goal) throw new Error(`${file}: block "${c.id}" has no //! goal`);
		c.lines.forEach((l, i) => {
			const plain = !l.trim() || /^[{}]$/.test(l.trim());
			if (!c.given && !plain && !c.notes[i]) throw new Error(`${file}: no //? note for "${l.trim()}" in block "${c.id}"`);
			if (plain && c.notes[i]) throw new Error(`${file}: //? note on a blank or brace line in block "${c.id}"`);
		});
	}
	return chunks;
}

// Lines marked //~ claim to be untouched exam code, so they must appear in the original file.
function checkContext(chunks, original, file) {
	const have = new Set(original.split('\n').map((l) => l.trim()));
	for (const c of chunks) c.lines.forEach((l, i) => {
		if (c.ctx[i] && !have.has(l.trim())) throw new Error(`${file}: //~ line "${l.trim()}" is not in the original`);
	});
}

function allowed(subject) {
	const m = subject.match(/Allowed functions\s*:\s*([\s\S]*?)\n\s*-{5,}/);
	return m ? m[1].replace(/\s+/g, ' ').split(',').map((s) => s.trim()).filter(Boolean) : [];
}

const data = {
	ranks: RANKS.map((rank) => ({
		id: rank.id,
		name: rank.name,
		levels: rank.levels.map((level) => ({
			name: level.name,
			exercises: level.exercises.map((ex) => {
				const subject = res(ex.subject).replace(/\r/g, '').trimEnd();
				const original = ex.original ? res(ex.original).replace(/\r/g, '').trimEnd() : null;
				const chunks = parseChunks(sol(rank.id, ex.solution), ex.solution);
				if (original) checkContext(chunks, original, ex.solution);
				return {
					id: ex.id,
					name: ex.name,
					file: ex.solution,
					allowed: allowed(subject),
					subject,
					original,
					chunks,
				};
			}),
		})),
	})),
};

const out = path.join(__dirname, 'data.js');
fs.writeFileSync(out, '// Generated by build.js — do not edit by hand.\nwindow.EXAM_DATA = ' + JSON.stringify(data) + ';\n');
const n = data.ranks.reduce((a, r) => a + r.levels.reduce((b, l) => b + l.exercises.length, 0), 0);
console.log(`data.js written: ${n} exercises`);
